def _feats(**kv):
    return "|".join(f"{k}={v}" for k, v in sorted(kv.items(), key=lambda x: x[0].lower()))


def closed_class_lexicon():
    """Словарь «слово (нижний регистр) → список (UPOS, FEATS)»."""
    lex = {}

    def add(word, upos, feats="_"):
        lex.setdefault(word, [])
        if (upos, feats) not in lex[word]:
            lex[word].append((upos, feats))

    for person, number, forms in _PERSONAL:
        for case, w in zip(CASES, forms):
            add(w, "PRON", _feats(Case=case, Number=number, Person=person, PronType="Prs"))
    for person, number, forms in _POLITE:
        for case, w in zip(CASES, forms):
            add(w, "PRON", _feats(Case=case, Number=number, Person=person, Polite="Form", PronType="Prs"))
    for w in _DEMONSTRATIVE_DET:
        add(w, "DET", "PronType=Dem")
    for forms in _DEMONSTRATIVE_CASES.values():
        for case, w in zip(CASES, forms):
            add(w, "PRON", _feats(Case=case, PronType="Dem"))
    for forms in _INTERROGATIVE.values():
        for case, w in zip(CASES, forms):
            add(w, "PRON", _feats(Case=case, PronType="Int"))
    for w in _INTERROGATIVE_OTHER:
        add(w, "PRON", "PronType=Int")
    for w in _INDEFINITE_PRON:
        add(w, "PRON", "PronType=Ind")
    for kind, words in _DET_OTHER.items():
        for w in words:
            add(w, "DET", f"PronType={kind}")
    for w in _REFLEXIVE:
        add(w, "PRON", "PronType=Prs|Reflex=Yes")
    for w in ADPOSITIONS:
        add(w, "ADP")
    for w in CCONJ:
        add(w, "CCONJ")
    for w in SCONJ:
        add(w, "SCONJ")
    for w in PARTICLES:
        add(w, "PART")
    for w in ADVERBS:
        add(w, "ADV")
    for w in INTERJECTIONS:
        add(w, "INTJ")
    for w, f in AUX_FORMS.items():
        add(w, "AUX", f)
    for w in CARDINAL_WORDS:
        add(w, "NUM", "NumType=Card")
        for suf in ORDINAL_SUFFIXES:
            if w and (w + suf) not in lex:
                stem = w[:-1] if w.endswith(("ы", "і")) and suf[0] in "ыі" else w
                add(stem + suf, "NUM", "NumType=Ord")
    return lex
